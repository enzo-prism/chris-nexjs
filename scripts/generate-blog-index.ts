/**
 * Generates client/src/data/blogIndex.ts: a tiny, static index of the blog
 * seed (server/storage.ts) that client components can import synchronously.
 *
 * Why: RelatedServicePosts used to fetch /api/blog-posts after hydration, so
 * the server HTML and the first client render disagreed (React #418) and the
 * SSR HTML carried no related-article links. A static index renders the same
 * cards on the server and the client, with real internal links.
 *
 * Usage:  pnpm exec tsx scripts/generate-blog-index.ts
 * Check:  pnpm exec tsx scripts/blog-index.test.ts (fails on drift)
 *
 * Re-run after adding, retitling, re-dating, or re-categorizing a blog post.
 */
import fs from "fs";
import path from "path";
import { fileURLToPath, pathToFileURL } from "url";
import { stripMarkdownToPlainText } from "../shared/blog";
import { getSeedData } from "../server/storage/seed";

export const BLOG_INDEX_PATH = path.join(
  path.dirname(fileURLToPath(import.meta.url)),
  "..",
  "client",
  "src",
  "data",
  "blogIndex.ts",
);

export const EXCERPT_MAX = 160;

export type BlogIndexRecord = {
  readonly slug: string;
  readonly title: string;
  readonly excerpt: string;
  readonly category: string;
  readonly relatedServices: readonly string[];
  readonly date: string;
  readonly readTime: number | null;
};

/** The article's own opening, cut on a sentence (or word) boundary. */
export function buildExcerpt(content: string, max = EXCERPT_MAX): string {
  const lead =
    content
      .split(/\r?\n\s*\r?\n/)
      .map((paragraph) => stripMarkdownToPlainText(paragraph))
      .find((paragraph) => paragraph.length >= 40) ?? stripMarkdownToPlainText(content);
  if (lead.length <= max) return lead;

  const sentences = lead.match(/[^.!?]+[.!?]+["'’”)\]]*/g) ?? [];
  let excerpt = "";
  for (const raw of sentences) {
    const sentence = raw.trim();
    const candidate = excerpt ? `${excerpt} ${sentence}` : sentence;
    if (candidate.length > max) break;
    excerpt = candidate;
  }
  if (excerpt) return excerpt;

  const cut = lead.slice(0, max - 1);
  const lastSpace = cut.lastIndexOf(" ");
  return `${cut.slice(0, lastSpace > 0 ? lastSpace : cut.length).replace(/[\s,;:.–—-]+$/, "")}…`;
}

export async function buildBlogIndexRecords(): Promise<BlogIndexRecord[]> {
  // getBlogPosts() already returns newest first (shared/blog sortItemsByDateDesc).
  const { blogPosts } = await getSeedData();
  return blogPosts.map((post) => ({
    slug: post.slug,
    title: post.title,
    excerpt: buildExcerpt(post.content),
    category: post.category?.trim() || "Dental Health",
    relatedServices: [...(post.relatedServices ?? [])],
    date: post.date,
    readTime: post.readTime ?? null,
  }));
}

export async function buildBlogIndexSource(): Promise<string> {
  const records = await buildBlogIndexRecords();
  const rows = records.map((record) => `  ${JSON.stringify(record)},`).join("\n");
  return `// AUTO-GENERATED by scripts/generate-blog-index.ts from the blog seed in
// server/storage.ts. Do not edit by hand: re-run the generator and commit.
// scripts/blog-index.test.ts fails when this file drifts from the seed.
// Kept tiny on purpose: it ships to the browser on service pages.

export type BlogIndexEntry = {
  readonly slug: string;
  readonly title: string;
  /** The article's opening, at most ${EXCERPT_MAX} characters. */
  readonly excerpt: string;
  readonly category: string;
  readonly relatedServices: readonly string[];
  /** Display date from the seed, e.g. "June 25, 2026". */
  readonly date: string;
  readonly readTime: number | null;
};

/** Every published post, newest first. */
export const blogIndex: readonly BlogIndexEntry[] = [
${rows}
];
`;
}

async function main(): Promise<void> {
  const source = await buildBlogIndexSource();
  fs.writeFileSync(BLOG_INDEX_PATH, source);
  const count = (source.match(/^ {2}\{"slug"/gm) ?? []).length;
  console.log(
    `[blog-index] wrote ${path.relative(process.cwd(), BLOG_INDEX_PATH)} (${count} posts, ${Buffer.byteLength(source)} bytes)`,
  );
}

const invokedDirectly =
  typeof process.argv[1] === "string" &&
  import.meta.url === pathToFileURL(path.resolve(process.argv[1])).href;

if (invokedDirectly) {
  main().catch((error) => {
    console.error(error);
    process.exit(1);
  });
}
